CREATE TABLE stall_engineering_profile (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  stall_id BIGINT NOT NULL,
  cable_quantity INT NOT NULL DEFAULT 0,
  cable_model VARCHAR(255),
  load_power_kw DECIMAL(12,2),
  meter_location VARCHAR(255),
  water_supply TINYINT(1) NOT NULL DEFAULT 0,
  water_meter_caliber VARCHAR(64),
  water_meter_location VARCHAR(255),
  drainage_available TINYINT(1) NOT NULL DEFAULT 0,
  drainage_pipe_caliber VARCHAR(64),
  drainage_pipeline_no VARCHAR(128),
  exhaust_duct_available TINYINT(1) NOT NULL DEFAULT 0,
  exhaust_duct_no VARCHAR(128),
  fresh_air_duct_available TINYINT(1) NOT NULL DEFAULT 0,
  fresh_air_duct_no VARCHAR(128),
  air_conditioner_quantity INT NOT NULL DEFAULT 0,
  fan_coil_quantity INT NOT NULL DEFAULT 0,
  hanging_cabinet_quantity INT NOT NULL DEFAULT 0,
  air_outlet_quantity INT NOT NULL DEFAULT 0,
  air_conditioner_model VARCHAR(255),
  gas_condition_available TINYINT(1) NOT NULL DEFAULT 0,
  gas_connected TINYINT(1) NOT NULL DEFAULT 0,
  gas_type VARCHAR(64),
  gas_pipe_quantity INT NOT NULL DEFAULT 0,
  gas_pipe_caliber VARCHAR(64),
  gas_pipeline_no VARCHAR(128),
  gas_interface_location VARCHAR(255),
  gas_meter_no VARCHAR(128),
  gas_meter_model VARCHAR(128),
  gas_meter_location VARCHAR(255),
  design_gas_flow DECIMAL(12,3),
  design_gas_load_kw DECIMAL(12,2),
  gas_valve_no VARCHAR(128),
  gas_alarm TINYINT(1) NOT NULL DEFAULT 0,
  gas_alarm_quantity INT NOT NULL DEFAULT 0,
  auto_shutoff_valve TINYINT(1) NOT NULL DEFAULT 0,
  gas_accepted TINYINT(1) NOT NULL DEFAULT 0,
  gas_acceptance_date DATE,
  gas_acceptance_org VARCHAR(255),
  remark VARCHAR(1000),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_sep_stall (stall_id),
  CONSTRAINT fk_sep_stall FOREIGN KEY (stall_id) REFERENCES stall(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
