CREATE TABLE field_verification_task (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  task_no VARCHAR(32) NOT NULL,
  workflow_id BIGINT NOT NULL,
  access_token VARCHAR(64) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  assigned_user_id BIGINT,
  assigned_user_name VARCHAR(64),
  opened_at DATETIME(3),
  started_at DATETIME(3),
  completed_at DATETIME(3),
  verification_result VARCHAR(32),
  remark VARCHAR(500),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_fvt_task_no (task_no),
  UNIQUE KEY uk_fvt_workflow (workflow_id),
  UNIQUE KEY uk_fvt_token (access_token),
  KEY idx_fvt_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE field_verification_device (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  verification_task_id BIGINT NOT NULL,
  workflow_device_id BIGINT NOT NULL,
  platform_device_id VARCHAR(64) NOT NULL,
  device_name_snapshot VARCHAR(255),
  energy_type VARCHAR(32),
  expected_comm_address VARCHAR(128),
  expected_serial_number VARCHAR(128),
  onsite_meter_number VARCHAR(128),
  onsite_serial_number VARCHAR(128),
  onsite_reading DECIMAL(20,6),
  reading_unit VARCHAR(16),
  device_matched TINYINT(1),
  serial_matched TINYINT(1),
  address_matched TINYINT(1),
  verification_result VARCHAR(32),
  verified_at DATETIME(3),
  remark VARCHAR(500),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_fvd_task_device (verification_task_id, platform_device_id),
  KEY idx_fvd_workflow_device (workflow_device_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

