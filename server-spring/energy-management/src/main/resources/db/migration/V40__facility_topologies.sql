CREATE TABLE facility_topology_node (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  system_type VARCHAR(32) NOT NULL,
  parent_id BIGINT NULL,
  node_code VARCHAR(64) NOT NULL,
  node_name VARCHAR(120) NOT NULL,
  node_type VARCHAR(64) NOT NULL,
  line_spec_code VARCHAR(64) NULL,
  equipment_spec_code VARCHAR(64) NULL,
  medium_type VARCHAR(64) NULL,
  design_flow DECIMAL(12,2) NULL,
  design_pressure DECIMAL(12,3) NULL,
  slope_percent DECIMAL(8,3) NULL,
  elevation_m DECIMAL(10,3) NULL,
  outlet_quantity INT NULL,
  control_component VARCHAR(200) NULL,
  location VARCHAR(200) NULL,
  stall_id BIGINT NULL,
  platform_device_id VARCHAR(100) NULL,
  operating_status VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
  sort_order INT NOT NULL DEFAULT 0,
  status TINYINT NOT NULL DEFAULT 1,
  remark VARCHAR(500) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_facility_topology_code (system_type,node_code),
  KEY idx_facility_topology_parent (system_type,parent_id,sort_order),
  KEY idx_facility_topology_stall (stall_id),
  CONSTRAINT fk_facility_topology_parent FOREIGN KEY (parent_id) REFERENCES facility_topology_node(id),
  CONSTRAINT fk_facility_topology_stall FOREIGN KEY (stall_id) REFERENCES stall(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='供水、排水、排油烟和补风拓扑节点';

