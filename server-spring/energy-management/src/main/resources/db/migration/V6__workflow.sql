CREATE TABLE workflow (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  workflow_no VARCHAR(32) NOT NULL,
  workflow_type VARCHAR(48) NOT NULL,
  merchant_code VARCHAR(6) NOT NULL,
  merchant_name VARCHAR(128) NOT NULL,
  contact_name VARCHAR(64),
  contact_phone VARCHAR(32),
  stall_id BIGINT NOT NULL,
  target_account_number VARCHAR(64),
  requested_billing_start_time DATETIME(3),
  applicant_id BIGINT,
  applicant_name VARCHAR(64),
  status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
  submitted_at DATETIME(3),
  field_verified_at DATETIME(3),
  waiting_platform_at DATETIME(3),
  verified_at DATETIME(3),
  completed_at DATETIME(3),
  expected_account_action VARCHAR(32),
  remark VARCHAR(500),
  extra_data JSON,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_workflow_no (workflow_no),
  KEY idx_workflow_status (status),
  KEY idx_workflow_type (workflow_type),
  KEY idx_workflow_merchant (merchant_code),
  KEY idx_workflow_stall (stall_id),
  KEY idx_workflow_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE workflow_device (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  workflow_id BIGINT NOT NULL,
  platform_device_id VARCHAR(64) NOT NULL,
  device_name_snapshot VARCHAR(255),
  energy_type_snapshot VARCHAR(32),
  comm_address_snapshot VARCHAR(128),
  serial_number_snapshot VARCHAR(128),
  gateway_name_snapshot VARCHAR(255),
  channel_name_snapshot VARCHAR(255),
  old_account_number VARCHAR(64),
  target_account_number VARCHAR(64),
  operation_type VARCHAR(16) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_workflow_device (workflow_id, platform_device_id),
  KEY idx_wd_device (platform_device_id),
  KEY idx_wd_workflow (workflow_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE workflow_expected_change (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  workflow_id BIGINT NOT NULL,
  change_type VARCHAR(32) NOT NULL,
  platform_device_id VARCHAR(64),
  from_account_number VARCHAR(64),
  to_account_number VARCHAR(64),
  expected_effective_time DATETIME(3),
  verify_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  actual_account_number VARCHAR(64),
  verified_at DATETIME(3),
  exception_reason VARCHAR(500),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_wec_workflow (workflow_id),
  KEY idx_wec_device (platform_device_id),
  KEY idx_wec_verify (verify_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
